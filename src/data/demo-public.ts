const now = Date.now()

function hoursAgo(h: number) {
  return new Date(now - h * 60 * 60 * 1000).toISOString()
}

function daysFromNow(d: number) {
  return new Date(now + d * 24 * 60 * 60 * 1000).toISOString()
}

